def decode_audio(path):
    r = subprocess.run(["ffmpeg", "-v", "error", "-i", path, "-f", "f32le", "-ac", "1", "-ar", str(SR), "-"], capture_output=True)
    if r.returncode != 0 or not r.stdout: raise RuntimeError("audio decode failed")
    return np.frombuffer(r.stdout, np.float32).copy()

def fake_voice(text):
    """offline test voice: one soft blip per word"""
    words = text.split(); out = []; ev = []; t = 0.0
    for w in words:
        n = int(0.30 * SR); tt = np.arange(n) / SR
        out.append((np.sin(2 * np.pi * (180 + 20 * (len(w) % 5)) * tt) * np.exp(-tt * 7) * 0.4).astype(np.float32))
        out.append(np.zeros(int(0.06 * SR), np.float32)); ev.append((t, 0.30, w)); t += 0.36
    return np.concatenate(out), ev

async def _edge(text, path, voice):
    import edge_tts
    try: comm = edge_tts.Communicate(text, voice, rate=VOICE_RATE, boundary="WordBoundary")
    except TypeError: comm = edge_tts.Communicate(text, voice, rate=VOICE_RATE)
    ev = []
    with open(path, "wb") as f:
        async for ch in comm.stream():
            if ch["type"] == "audio": f.write(ch["data"])
            elif ch["type"] == "WordBoundary": ev.append((ch["offset"] / 1e7, ch["duration"] / 1e7, ch["text"]))
    return ev

