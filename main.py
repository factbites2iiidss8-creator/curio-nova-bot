def next_slot(state):
    """first free slot (at least 25 min from now). Minutes are jittered by up to 5 min so posting times look natural."""
    now = utcnow(); taken = set(state.get("scheduled", []))
    for day in range(0, 14):
        base = (now + dt.timedelta(days=day)).replace(hour=0, minute=0, second=0, microsecond=0)
        for idx, hhmm in enumerate(SCHEDULE[base.weekday()]["times"]):
            h, m = [int(x) for x in hhmm.split(":")]
            jit = random.Random(base.strftime("%Y%m%d") + str(idx)).randint(-5, 5)
            t = base + dt.timedelta(hours=h, minutes=m + jit)
            if t >= now + dt.timedelta(minutes=25) and t.strftime(ISO) not in taken: return t.strftime(ISO), t, idx
    t = now + dt.timedelta(hours=2); return t.strftime(ISO), t, 0

