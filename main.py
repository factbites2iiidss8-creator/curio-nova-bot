    small = fr.resize((W // 8, H // 8), Image.Resampling.BILINEAR).filter(ImageFilter.GaussianBlur(2.5)).resize((W, H), Image.Resampling.BICUBIC)
    bg = Image.blend(small, BLACK, .45); acc = P["pal"]["acc"]
    if style == "frame":
        tw, th = int(W * .86), int(H * .56)
        card = Image.new("RGBA", (tw + 16, th + 16), (255, 255, 255, 255)); card.paste(ImageOps_fit(fr, (tw, th)), (8, 8))
        card.putalpha(_rmask(tw + 16, th + 16, 28))
