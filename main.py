def movavg(x, w):
    c = np.cumsum(np.insert(np.abs(x), 0, 0)); ma = (c[w:] - c[:-w]) / w
    return np.concatenate([np.full(w // 2, ma[0]), ma, np.full(len(x) - len(ma) - w // 2, ma[-1])])

def tone(freq, dur, kind="sine", a=.01, dec=3.0):
    t = np.arange(int(dur * SR)) / SR; p = 2 * np.pi * freq * t
    if kind == "bell": w = np.sin(p) + .5 * np.sin(p * 2.76) * np.exp(-t * 6) + .25 * np.sin(p * 5.4) * np.exp(-t * 10)
    elif kind == "pluck": w = np.sin(p) + .5 * np.sin(2 * p) + .3 * np.sin(3 * p) + .15 * np.sin(4 * p)
    elif kind == "pad": w = np.sin(p) + .5 * np.sin(p * 1.004 * 2) + .3 * np.sin(p * .997)
    else: w = np.sin(p)
    return (w * np.minimum(t / a, 1) * np.exp(-t * dec)).astype(np.float32)

def pad_note(freq, dur):
    t = np.arange(int(dur * SR)) / SR; p = 2 * np.pi * freq * t
    w = np.sin(p) + .45 * np.sin(p * 2.003) + .3 * np.sin(p * .998)
    return (w * np.minimum(t / .6, 1) * np.minimum((dur - t) / .6, 1)).astype(np.float32)

def add(buf, start, snd, gain=1.0):
    s = int(start * SR)
    if s < 0 or s >= len(buf): return
    e = min(len(buf), s + len(snd)); buf[s:e] += snd[:e - s] * gain

def kick():
    t = np.arange(int(.35 * SR)) / SR; f = 45 + 90 * np.exp(-t * 28)
    return (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)).astype(np.float32)

def hat(rng):
    t = np.arange(int(.05 * SR)) / SR; n = rng.standard_normal(len(t)); return (np.diff(n, prepend=0) * np.exp(-t * 70) * .5).astype(np.float32)

def sfx(kind, rng):
    if kind in ("whoosh", "swell"):
        n = int((.55 if kind == "whoosh" else .8) * SR); t = np.arange(n) / SR; T = n / SR
        env = np.sin(np.pi * np.clip(t / T, 0, 1)) ** (1.5 if kind == "whoosh" else 2.5)
        noise = np.convolve(rng.standard_normal(n), np.ones(6) / 6, "same") * env
        f = 300 + 2400 * (t / T) ** 2; ch = np.sin(2 * np.pi * np.cumsum(f) / SR) * env
        return (noise * .5 + ch * .25).astype(np.float32)
    if kind == "impact":
        n = int(.7 * SR); t = np.arange(n) / SR; f = 40 + 90 * np.exp(-t * 14)
        return (np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 5) * .9 + rng.standard_normal(n) * np.exp(-t * 40) * .35).astype(np.float32)
    if kind == "sparkle":
        out = np.zeros(int(.9 * SR), np.float32)
        for i, fr in enumerate((1568, 2093, 2637, 3136, 3951)): add(out, i * .07, tone(fr, .4, "bell", dec=7), .35)
        return out
    if kind == "riser":
        n = int(.9 * SR); t = np.arange(n) / SR; env = (t / (n / SR)) ** 2
        f = 200 + 1800 * (t / (n / SR)) ** 2
        return ((np.convolve(rng.standard_normal(n), np.ones(5) / 5, "same") * .4 + np.sin(2 * np.pi * np.cumsum(f) / SR) * .3) * env).astype(np.float32)
    if kind == "tick": return tone(1500, .05, "sine", a=.001, dec=70) * .6
    if kind == "chime": return tone(1046, 1.4, "bell", dec=2.2) * .5 + tone(1568, 1.4, "bell", dec=2.6) * .3
    return np.zeros(10, np.float32)

def make_music(D, pack_key, rng):
    P = PACKS[pack_key]; buf = np.zeros(int(D * SR) + SR, np.float32)
    beat = 60 / P["bpm"]; sc = P["scale"]; n = len(sc); root = P["root"]; kindv = P["voice"]
    f = lambda deg, o=0: root * 2 ** ((sc[deg % n] + 12 * (deg // n) + 12 * o) / 12)
    prog = [0, 3, 4, 2]; t = 0.0; bar = 0
    while t < D:
        ch = prog[bar % 4]
        for off in (0, 2, 4): add(buf, t, pad_note(f(ch + off), beat * 4 + .6), .16)
        add(buf, t, tone(f(ch, -1), beat * 2, "sine", a=.02, dec=1.6), .32)
        for st in range(8):
            deg = ch + (0, 2, 4, 2, 5, 4, 2, 1)[st]
            if P["fx"] in ("twinkle", "sparkle") and st % 2: continue
            add(buf, t + st * beat / 2, tone(f(deg, 1), .5, kindv if kindv != "soft" else "bell", dec=5), .13)
        if P["fx"] in ("sparks", "embers"):
            for b in range(4):
                if b % 2 == 0 or P["fx"] == "embers": add(buf, t + b * beat, kick(), .5)
                add(buf, t + b * beat + beat / 2, hat(rng), .5)
        if P["fx"] == "cells":
            for b in range(4):
                add(buf, t + b * beat * 1.0, tone(58, .25, "sine", a=.005, dec=12), .55); add(buf, t + b * beat + .28, tone(52, .22, "sine", a=.005, dec=14), .4)
        t += beat * 4; bar += 1
    return buf / (np.max(np.abs(buf)) + 1e-6)

def mix_audio(voice, D, events, pack_key, rng):
    voice = voice.copy()
    if np.max(np.abs(voice)) > 0: voice *= .8 / np.max(np.abs(voice))
    music = make_music(D, pack_key, rng)[:len(voice)]
    duck = 1 - .65 * np.clip(movavg(voice, 2205) / .08, 0, 1)
    out = voice * .95 + music * duck * .22
    s = np.zeros(len(voice), np.float32)
    for (tt, kind) in events: add(s, tt, sfx(kind, rng), .55)
    out = out + s
    return out * (.89 / (np.max(np.abs(out)) + 1e-6))

def write_wav(path, x):
    pcm = (np.clip(x, -1, 1) * 32767).astype(np.int16); st = np.stack([pcm, pcm], 1)
    with wave.open(path, "wb") as w:
        w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(st.tobytes())

