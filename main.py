_FONTS = {}
def font(size):
    size = int(size)
    if size not in _FONTS:
        try: _FONTS[size] = ImageFont.truetype(_font_path(), size)
        except Exception: _FONTS[size] = ImageFont.load_default()
    return _FONTS[size]

def text_w(d, t, size): return d.textlength(t, font=font(size))
def outlined(d, xy, t, size, fill, stroke=6, anchor="mm"):
    d.text(xy, t, font=font(size), fill=fill, anchor=anchor, stroke_width=stroke, stroke_fill=(10, 10, 20, 255))
def wrap(d, text, size, maxw):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if text_w(d, t, size) <= maxw or not cur: cur = t
        else: lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines

def vgrad(w, h, c1, c2):
    t = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    a = np.array(c1, np.float32)[None, None, :]; b = np.array(c2, np.float32)[None, None, :]
    return Image.fromarray(((a + (b - a) * t) * np.ones((1, w, 1), np.float32)).astype(np.uint8), "RGB")

