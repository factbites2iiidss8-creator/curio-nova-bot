def upload(video, thumb, script, publish_at):
    from googleapiclient.http import MediaFileUpload
    yt = yt_service()
    desc = (script["description"] + "\n\n" + " ".join(script["hashtags"]) + f" #Shorts #{re.sub(r'[^A-Za-z0-9]', '', CHANNEL)}").strip()[:4900]
    tags, total = [], 0
    for t in script["tags"] + [CHANNEL, "shorts"]:
        if total + len(t) + 1 > 450: break
        tags.append(t); total += len(t) + 1
    body = {"snippet": {"title": script["title"][:95], "description": desc, "tags": tags, "categoryId": "27", "defaultLanguage": "en", "defaultAudioLanguage": "en"},
            "status": {"privacyStatus": "private", "publishAt": publish_at, "selfDeclaredMadeForKids": False, "containsSyntheticMedia": True}}
    last = None
    for attempt in range(3):
        try:
            req = yt.videos().insert(part="snippet,status", body=body, media_body=MediaFileUpload(video, mimetype="video/mp4", chunksize=8 * 1024 * 1024, resumable=True))
            resp = None
            while resp is None: _, resp = req.next_chunk(num_retries=3)
            vid = resp["id"]; log("uploaded:", vid, "publishAt", publish_at)
            if thumb:
                try: yt.thumbnails().set(videoId=vid, media_body=MediaFileUpload(thumb, mimetype="image/jpeg")).execute()
                except Exception as e: log("thumbnail skipped:", e)
            return vid
        except Exception as e:
            last = e; log("upload retry:", e); time.sleep(10 * (attempt + 1))
    raise RuntimeError(f"upload failed: {last}")

