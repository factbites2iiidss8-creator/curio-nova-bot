def offline_script(pack_key, state):
    used = {u.get("topic") for u in state.get("used", [])}
    pool = [b for b in BANK if b["pack"] == pack_key and b["topic"] not in used] or [b for b in BANK if b["topic"] not in used] or BANK
    b = random.choice(pool)
    d = dict(topic=b["topic"], title=b["title"], description=b["desc"] + "\n" + FOLLOW, hashtags=["#science", "#facts", "#anime"],
             tags=["science facts", "did you know", "anime", "shorts"], style_anchor=b["anchor"],
             scenes=[dict(text=t, image=i) for t, i in b["scenes"]])
    return normalize_script(d, b["pack"])

def write_script(state, pack_key):
    used = [u.get("topic", "") for u in state.get("used", [])][-80:]
    if OFFLINE: return offline_script(pack_key, state)
    for attempt in range(3):
        try:
            s = normalize_script(llm_json(script_prompt(pack_key, used)), pack_key)
        except Exception as e:
            log("script attempt failed:", e); continue
        ok, why = verify(s)
        log(f"topic: {s['topic']} | fact-check ok={ok} {why}")
        if ok: return s
    log("LLMs unavailable or fact-check kept failing -> using the built-in fact bank")
    return offline_script(pack_key, state)

