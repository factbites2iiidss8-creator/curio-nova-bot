_GM = {}
GEM_FALLBACK = ["gemini-3.8-flash", "gemini-3.7-flash", "gemini-3.6-flash", "gemini-3.5-flash", "gemini-3.5-flash-lite", "gemini-2.5-flash"]
def _gkey(): return os.environ.get("GEMINI_API_KEY", "").strip()

def gem_names(kind):
    """auto-discover the models this key can use (newest stable first)"""
    if "all" not in _GM:
        try:
            r = requests.get("https://generativelanguage.googleapis.com/v1beta/models?pageSize=200", headers={"x-goog-api-key": _gkey()}, timeout=30)
            _GM["all"] = r.json().get("models", []) if r.ok else []
        except Exception:
            _GM["all"] = []
    found = []
    for m in _GM["all"]:
        name = m.get("name", "").split("/")[-1]
        if "generateContent" not in m.get("supportedGenerationMethods", []): continue
        bad = any(x in name for x in ("tts", "live", "audio", "embedding", "robotics", "computer", "native", "learnlm"))
        if kind == "text" and "flash" in name and "image" not in name and not bad: found.append(name)
        if kind == "image" and "image" in name and not bad: found.append(name)
    def key(n):
        v = re.findall(r"\d+(?:\.\d+)?", n)
        ver = float(v[0]) if v else 0.0
        return (1 if ("preview" in n or "exp" in n) else 0, -ver, 1 if "lite" in n else 0, 0 if "flash" in n else 1)
    found.sort(key=key)
    return found + ([x for x in GEM_FALLBACK if x not in found] if kind == "text" else [])

def parse_json(txt):
    t = re.sub(r"^```(?:json)?|```$", "", txt.strip(), flags=re.M).strip()
    try: return json.loads(t)
    except Exception:
        s, e = t.find("{"), t.rfind("}")
        return json.loads(t[s:e + 1])

def gemini_text(prompt):
    if not _gkey(): raise RuntimeError("no GEMINI_API_KEY")
    body = {"contents": [{"parts": [{"text": prompt}]}], "generationConfig": {"responseMimeType": "application/json"}}
    last = None
    for rnd in range(2):
        for m in gem_names("text")[:5]:
            try:
                r = requests.post(f"https://generativelanguage.googleapis.com/v1beta/models/{m}:generateContent", headers={"x-goog-api-key": _gkey()}, json=body, timeout=120)
                if not r.ok:
                    last = f"{m} {r.status_code}"; log("gemini error:", last, r.text[:120]); time.sleep(3); continue
                parts = r.json()["candidates"][0]["content"]["parts"]
                return "".join(p.get("text", "") for p in parts if not p.get("thought"))
            except Exception as e:
                last = f"{m} {e}"; log("gemini exception:", last); time.sleep(3)
        time.sleep(15)
    raise RuntimeError(f"gemini failed: {last}")

def openai_text(prompt):
    key = os.environ.get("OPENAI_API_KEY", "").strip()
    if not key: raise RuntimeError("no OPENAI_API_KEY")
    last = None
    for model in [os.getenv("OPENAI_MODEL", "")] + ["gpt-4o-mini", "gpt-4.1-mini"]:
        if not model: continue
        try:
            r = requests.post("https://api.openai.com/v1/chat/completions", headers={"Authorization": "Bearer " + key}, timeout=120,
                              json={"model": model, "response_format": {"type": "json_object"},
                                    "messages": [{"role": "system", "content": "Return ONLY valid JSON."}, {"role": "user", "content": prompt}]})
            if r.ok: return r.json()["choices"][0]["message"]["content"]
            last = f"{model} {r.status_code}"; log("openai error:", last, r.text[:120])
        except Exception as e:
            last = f"{model} {e}"; log("openai exception:", last)
    raise RuntimeError(f"openai failed: {last}")

def llm_json(prompt):
    errs = []
    for fn in (gemini_text, openai_text):
        try: return parse_json(fn(prompt))
        except Exception as e: errs.append(f"{fn.__name__}: {e}"); log("LLM step failed ->", errs[-1])
    raise RuntimeError("all LLMs failed: " + " | ".join(errs))

