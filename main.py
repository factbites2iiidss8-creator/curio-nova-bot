def _rmask(w, h, r):
    key = (w, h, r)
    if key not in _RM:
        m = Image.new("L", (w * 2, h * 2), 0); ImageDraw.Draw(m).rounded_rectangle([0, 0, w * 2 - 1, h * 2 - 1], radius=r * 2, fill=255)
        _RM[key] = m.resize((w, h), Image.Resampling.LANCZOS)
    return _RM[key]

def layout_frame(fr, sc, t, P):
    """full-screen picture, or the picture inside a rounded 'frame' or a round 'lens' over a blurred copy of itself (keeps every scene looking different)"""
