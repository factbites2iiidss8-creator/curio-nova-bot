def wrap(d, text, size, maxw):
    lines, cur = [], ""
    for w in text.split():
        t = (cur + " " + w).strip()
        if text_w(d, t, size) <= maxw or not cur: cur = t
        else: lines.append(cur); cur = w
    if cur: lines.append(cur)
    return lines

def vgrad(w, h, c1, c2):
    t = np.linspace(0, 1, h, dtype=np.float32)[:, None, None]
    a = np.array(c1, np.float32)[None, None, :]; b = np.array(c2, np.float32)[None, None, :]
    return Image.fromarray(((a + (b - a) * t) * np.ones((1, w, 1), np.float32)).astype(np.uint8), "RGB")

