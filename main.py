def scene_frame(sc, t):
    t = clamp(t, 0, sc.dur); k = t / max(sc.dur, .01)
    if sc.vid is not None:
        fr = sc.vid.frame(int(t * FPS)).copy()
    else:
        z, cx, cy = camera(sc.motion, smooth(k), sc.seed % 7)
        vw = IW * .86 / z; vh = vw * H / W; px, py = cx * IW, cy * IH
        if sc.sfx == "impact":
            a = 16 * math.exp(-t * 8); px += a * math.sin(t * 55); py += a * math.cos(t * 47)
        x0 = clamp(px - vw / 2, 0, IW - vw); y0 = clamp(py - vh / 2, 0, IH - vh)
        fr = sc.img.transform((W, H), Image.Transform.AFFINE, (vw / W, 0, x0, 0, vh / H, y0), resample=Image.Resampling.BICUBIC)
    fr = layout_frame(fr, sc, t, PACKS[sc.pack])
    fr = Image.composite(fr, BLACK, VIG)
    draw_fx(fr, sc, t, PACKS[sc.pack])
    return fr

def blend(prev, cur, k, kind):
    k = clamp(k)
    if kind == "fade": return Image.blend(prev, cur, eo3(k))
    if kind == "flash":
        white = Image.new("RGB", (W, H), (255, 255, 255))
        return Image.blend(prev, white, k * 2) if k < .5 else Image.blend(white, cur, (k - .5) * 2)
    if kind in ("slide_l", "slide_u"):
        off = int((1 - eo3(k)) * (W if kind == "slide_l" else H)); c = prev.copy()
        c.paste(cur, (off, 0) if kind == "slide_l" else (0, off)); return c
    rad = int(eo3(k) * math.hypot(W, H) / 2 * 1.02); m = Image.new("L", (W, H), 0)
    ImageDraw.Draw(m).ellipse([W / 2 - rad, H / 2 - rad, W / 2 + rad, H / 2 + rad], fill=255)
    return Image.composite(cur, prev, m)

def caption_chunks(words):
    chunks, cur = [], []
    for w in words:
        cur.append(w)
        if len(cur) >= 3 or re.search(r"[.,!?;:]$", w[2]) or sum(len(x[2]) for x in cur) > 16: chunks.append(cur); cur = []
    if cur: chunks.append(cur)
    return chunks

