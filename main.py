def normalize_script(d, pack_key):
    scenes = []
    for i, s in enumerate(d["scenes"]):
        text = re.sub(r"\s+", " ", str(s.get("text", ""))).strip()
        if not text: continue
        img = re.sub(r"\b(cute |gritty )?anime( style)?\b", "", str(s.get("image") or text), flags=re.I).strip(" ,.")
        kw = str(s.get("keywords") or " ".join(img.split()[:3])); st = s.get("stat"); stat = None
        if isinstance(st, dict) and str(st.get("value", "")).strip(): stat = dict(value=str(st["value"]).strip()[:14], unit=str(st.get("unit", "")).strip().upper()[:18])
        img = f"{img}. Camera: {SHOTS[(i * 5 + len(str(d.get('topic', '')))) % len(SHOTS)]}"   # every scene gets a different shot type
        scenes.append(dict(text=text, image=img, keywords=kw, stat=stat,
                           motion=s.get("motion") if s.get("motion") in MOTIONS else MOTIONS[i % len(MOTIONS)],
                           sfx=s.get("sfx") if s.get("sfx") in SFXS else "none"))
    if len(scenes) < 5: raise ValueError("too few scenes")
    return dict(topic=str(d.get("topic") or scenes[0]["text"])[:80].replace("\n", " "),
                title=re.sub(r'["#]', "", str(d.get("title") or d.get("topic") or CHANNEL))[:90],
                description=str(d.get("description") or "").strip(),
                hashtags=[h if h.startswith("#") else "#" + h for h in (d.get("hashtags") or [])][:4],
                tags=[str(t) for t in (d.get("tags") or [])][:12],
                anchor=re.sub(r"\banime\b", "cinematic", str(d.get("style_anchor") or ""), flags=re.I), pack=pack_key, scenes=scenes)

def verify(script):
    facts = " ".join(s["text"] for s in script["scenes"])
    prompt = ("You are a strict science fact-checker. Check this short video narration for any false or misleading claim, "
              "wrong number, or unqualified superlative.\n" f'Narration: """{facts}"""\n'
              'Return ONLY JSON: {"ok": true or false, "issue": "short reason"}')
    try:
        d = llm_json(prompt); return bool(d.get("ok")), str(d.get("issue", ""))
    except Exception as e:
        log("fact-check unavailable:", e); return True, "checker unavailable"

