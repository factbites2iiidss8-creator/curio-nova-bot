def picture_sig(res):
    """tiny fingerprint of a picture (or of the first frame of a clip) to catch scenes that look the same"""
    if isinstance(res, str):
        v = VideoSrc(res); im = v.frame(10).copy(); v.close()
    else: im = res
    a = np.asarray(im.convert("L").resize((17, 16), Image.Resampling.BILINEAR), dtype=np.int16)
    return (a[:, 1:] > a[:, :-1]).flatten()

