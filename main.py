def word_timings(text, events, vlen):
    toks = text.split()
    if events and abs(len(events) - len(toks)) <= 2:
        st = [events[min(i, len(events) - 1)][0] for i in range(len(toks))]
    else:
        total = sum(len(t) + 2 for t in toks); usable = max(vlen - 0.15, 0.4); st = []; acc = 0.0
        for t in toks: st.append(acc / total * usable); acc += len(t) + 2
    return [(st[i], st[i + 1] if i + 1 < len(st) else vlen + 0.2, t) for i, t in enumerate(toks)]

